//! Rook's cryptography, written from the specifications.
//!
//! These primitives are built from scratch (Rook vendors no crates) and
//! checked against the official RFC and NIST known-answer vectors by
//! `self_test`, which runs in ring 3 at every boot. They are written to
//! be constant-time — no step branches on a key or a secret — but they
//! have not been audited, so nothing here protects anything real until it
//! has been. The design doc budgets that audit.
//!
//! What's here: SHA-256 and SHA-512, HMAC over both, HKDF, ChaCha20,
//! Poly1305, the ChaCha20-Poly1305 AEAD, X25519 key exchange and Ed25519
//! signatures. Drawbridge's session protocol is built from these.

#![cfg_attr(not(test), no_std)]
#![forbid(unsafe_code)]

