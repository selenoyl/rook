/// The RFC 8439 sample message, used by two of the vectors (§2.4.2, §2.8).
const SAMPLE: &[u8; 114] =
    b"Ladies and Gentlemen of the class of '99: If I could offer you only one tip for the future, sunscreen would be it.";

/// Run every primitive against its official known-answer vector. Returns
/// true only if all of them match. A single flipped constant or a wrong
/// rotation makes one fail, so this is a real check that the build is
/// correct, not a smoke test.
pub fn self_test() -> bool {
    sha2_ok()
        && sha3_ok()
        && hmac_ok()
        && hkdf_ok()
        && chacha_ok()
        && poly1305_ok()
        && aead_ok()
        && x25519_ok()
        && ed25519_ok()
        && mlkem_ok()
}

/// ML-KEM-768: keygen pinned to the NIST ACVP (FIPS 203) vector by the
/// hashes of its outputs, then an encapsulate/decapsulate round-trip and a
/// tampered-ciphertext rejection.
fn mlkem_ok() -> bool {
    let d = [
        0xe5, 0x82, 0xb7, 0xd7, 0x5e, 0x6c, 0x80, 0xb0, 0x5a, 0xe3, 0x92, 0xa1, 0xfc, 0x9f, 0x71,
        0x53, 0xb1, 0x23, 0x90, 0xfd, 0x99, 0x93, 0x03, 0x68, 0xcc, 0x67, 0xa7, 0x68, 0xba, 0xeb,
        0xc8, 0xa0,
    ];
    let z = [
        0x1c, 0xda, 0xcb, 0x87, 0x40, 0xc0, 0xb8, 0x7c, 0x4a, 0x37, 0x95, 0x75, 0xf1, 0x87, 0xb3,
        0x67, 0xcb, 0xfa, 0x3b, 0x30, 0x0b, 0xf5, 0x91, 0xb1, 0x09, 0xf7, 0x98, 0x16, 0xe9, 0xcb,
        0xe8, 0xf0,
    ];
    let want_ek = [
        0x81, 0xe6, 0x6e, 0xf5, 0xa7, 0xa2, 0x21, 0x61, 0x9f, 0x6a, 0x64, 0x03, 0x9c, 0xc3, 0x69,
        0x84, 0x3e, 0x10, 0xdf, 0x5c, 0x85, 0x9f, 0x69, 0x59, 0xcc, 0x3f, 0xd8, 0xe5, 0x27, 0x23,
        0x30, 0xfd,
    ];
    let want_dk = [
        0xbe, 0x81, 0x06, 0x8c, 0x10, 0x4c, 0xd6, 0xcf, 0x8e, 0xfd, 0x80, 0x0b, 0x29, 0x4f, 0x4a,
        0x15, 0xbb, 0x8a, 0x80, 0x50, 0x99, 0x3f, 0xd5, 0x4a, 0x2c, 0xc4, 0x28, 0x84, 0x1e, 0xf6,
        0xca, 0x44,
    ];

    let (ek, dk) = mlkem_keygen(&d, &z);
    if sha3_256(&ek) != want_ek || sha3_256(&dk) != want_dk {
        return false;
    }
    let m = [0x24u8; 32];
    let (mut c, shared) = mlkem_encaps(&ek, &m);
    if mlkem_decaps(&dk, &c) != shared {
        return false;
    }
    c[0] ^= 1;
    mlkem_decaps(&dk, &c) != shared
}

